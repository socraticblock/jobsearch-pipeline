#!/usr/bin/env python3
"""Onboard a new user: turn a CV + preferences into profile/profile.yaml.

    python3 tools/onboard.py --cv resume.txt --preferences prefs.yaml
    python3 tools/onboard.py --cv resume.pdf   # uses pdftotext if available

The gate's five fields are produced from inputs the user supplies; nothing is
guessed. Skills found in the CV are marked 'corroborated' (the user claimed
them by writing them); the user reviews and downgrades any they are unsure of.
Missing preferences fall back to the starter defaults and are printed as
"review these" rather than silently accepted.

Exit codes: 0 profile written | 1 missing input / bad usage | 2 extraction failed.
"""
from __future__ import annotations

import argparse
import re
import shutil
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

# Skill vocabulary. A skill is "held" only if the CV mentions it (case-insensitive,
# whole-word-ish). The list is deliberately conservative: a false positive here
# becomes a HELD technology in the gate, so prefer omission over invention.
SKILL_VOCAB = [
    "TypeScript", "JavaScript", "Python", "Go", "Rust", "Java", "C#", "C++",
    "React", "Next.js", "Vue", "Angular", "Svelte", "Node.js", "Express",
    "FastAPI", "Django", "Flask", "PostgreSQL", "MySQL", "MongoDB", "Redis",
    "SQLite", "Docker", "Kubernetes", "AWS", "GCP", "Azure", "Linux", "Git",
    "Playwright", "Vitest", "Jest", "GraphQL", "REST", "Tailwind", "Prisma",
    "Solidity", "Web3", "Ethereum", "MongoDB", "SQL", "HTML", "CSS",
    "Framer Motion", "TensorFlow", "PyTorch", "OpenAI", "LLM", "AI",
]

DEFAULT_PREFS = {
    "local_markets": ["Your city", "Your country"],
    "work_authorisation": ["eu"],
    "floor": "6000 EUR",
    "currency": "EUR",
    "floor_basis": "NET",
    "years": 5,
}


def extract_text(path: Path) -> str:
    suffix = path.suffix.lower()
    if suffix in (".txt", ".md", ".rst"):
        return path.read_text(encoding="utf-8", errors="replace")
    if suffix == ".pdf":
        pdftotext = shutil.which("pdftotext")
        if pdftotext:
            import subprocess

            out = path.with_suffix(".txt")
            subprocess.run([pdftotext, "-layout", str(path), str(out)], check=True)
            text = out.read_text(encoding="utf-8", errors="replace")
            try:
                out.unlink()
            except OSError:
                pass
            return text
        raise RuntimeError(
            "PDF given but 'pdftotext' is not installed. Convert the CV to .txt "
            "or install poppler-utils."
        )
    raise RuntimeError(f"unsupported CV format: {suffix} (use .txt, .md or .pdf)")


def extract_skills(text: str) -> list[str]:
    found: list[str] = []
    lowered = text.lower()
    for skill in SKILL_VOCAB:
        # word-ish boundary: skill token surrounded by non-word or string edges
        pattern = r"(?<![A-Za-z0-9])" + re.escape(skill.lower()) + r"(?![A-Za-z0-9])"
        if re.search(pattern, lowered):
            if skill not in found:
                found.append(skill)
    return found


def load_prefs(path: Path | None) -> dict:
    prefs = dict(DEFAULT_PREFS)
    if path is None:
        return prefs
    try:
        import yaml
    except ImportError:
        # Fall back to a tiny parser for the five keys we care about.
        yaml = None
    if yaml is not None:
        data = yaml.safe_load(path.read_text(encoding="utf-8")) or {}
        prefs.update({k: v for k, v in data.items() if v is not None})
        return prefs
    # Minimal fallback: key: value lines.
    for line in path.read_text(encoding="utf-8").splitlines():
        line = line.strip()
        if not line or line.startswith("#") or ":" not in line:
            continue
        key, _, val = line.partition(":")
        prefs[key.strip()] = val.strip().strip('"').strip("'")
    return prefs


def render_profile(skills: list[str], prefs: dict) -> str:
    lines: list[str] = []
    lines.append("# profile.yaml — generated by tools/onboard.py")
    lines.append("# Review every field. Skills found in the CV are marked 'corroborated';")
    lines.append("# downgrade any you are unsure of to 'learning' or 'aspirational'.")
    lines.append("")
    lines.append("stack:")
    if skills:
        for s in skills:
            lines.append(f"  - skill: {s}")
            lines.append("    status: corroborated")
    else:
        lines.append("  - skill: (add your skills here)")
        lines.append("    status: corroborated")
    lines.append("")
    lines.append("compensation:")
    lines.append(f'  floor: "{prefs.get("floor", DEFAULT_PREFS["floor"])}"')
    lines.append(f'  currency: {prefs.get("currency", DEFAULT_PREFS["currency"])}')
    lines.append(f'  floor_basis: {prefs.get("floor_basis", DEFAULT_PREFS["floor_basis"])}')
    lines.append("")
    lines.append("location_and_arrangement:")
    lines.append("  local_markets:")
    for m in prefs.get("local_markets", DEFAULT_PREFS["local_markets"]):
        lines.append(f'    - "{m}"')
    lines.append("  authorization:")
    lines.append("    work_authorisation:")
    for a in (prefs.get("work_authorisation", DEFAULT_PREFS["work_authorisation"])
              if isinstance(prefs.get("work_authorisation", DEFAULT_PREFS["work_authorisation"]), list)
              else [prefs.get("work_authorisation", "eu")]):
        lines.append(f'      - "{a}"')
    lines.append("")
    lines.append(f'years_can_honestly_claim: {prefs.get("years", DEFAULT_PREFS["years"])}')
    lines.append("")
    return "\n".join(lines)


def run_wizard() -> dict:
    """Interactive 5-question wizard. Returns a prefs dict."""
    def ask(prompt: str, default: str = "") -> str:
        suffix = f" [{default}]" if default else ""
        try:
            answer = input(f"{prompt}{suffix}: ").strip()
        except EOFError:
            answer = ""
        return answer if answer else default

    print("Onboarding wizard — answer 5 questions. Press Enter to accept the default.")
    city = ask("Your city (local market)", "Your city")
    country = ask("Your country", "Your country")
    scopes_raw = ask("Work authorisation scopes (comma-separated, e.g. eu,us)", "eu")
    scopes = [s.strip() for s in scopes_raw.split(",") if s.strip()]
    if not scopes:
        scopes = ["eu"]
    floor_raw = ask("Pay floor + currency (e.g. 6000 EUR)", "6000 EUR")
    parts = floor_raw.split()
    floor = floor_raw
    currency = parts[-1] if len(parts) > 1 else "EUR"
    years_raw = ask("Years you can honestly claim", "5")
    try:
        years = int(years_raw)
    except ValueError:
        years = 5
    return {
        "local_markets": [city, country],
        "work_authorisation": scopes,
        "floor": floor,
        "currency": currency,
        "floor_basis": "NET",
        "years": years,
    }

def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description="Onboard: CV + preferences -> profile/profile.yaml")
    ap.add_argument("--cv", type=Path, required=True, help="path to CV (.txt, .md, .pdf)")
    ap.add_argument("--preferences", type=Path, default=None, help="YAML preferences file")
    ap.add_argument("--out", type=Path, default=Path.home() / ".config" / "jobsearch" / "profile.yaml")
    ap.add_argument("--no-interactive", action="store_true",
                    help="do not prompt; use starter defaults for missing prefs")
    args = ap.parse_args(argv)

    if not args.cv.is_file():
        print(f"CV not found: {args.cv}", file=sys.stderr)
        return 1
    try:
        text = extract_text(args.cv)
    except RuntimeError as exc:
        print(f"extraction failed: {exc}", file=sys.stderr)
        return 2

    skills = extract_skills(text)

    if args.preferences is not None:
        prefs = load_prefs(args.preferences)
    elif args.no_interactive or not sys.stdin.isatty():
        prefs = load_prefs(None)
        if not args.no_interactive:
            print("stdin is not a tty; using starter defaults. "
                  "Pass --preferences or run interactively.", file=sys.stderr)
    else:
        prefs = run_wizard()

    profile_text = render_profile(skills, prefs)
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(profile_text, encoding="utf-8")
    print(f"wrote {args.out}")
    print(f"skills found in CV ({len(skills)}): {', '.join(skills) if skills else '(none)'}")
    if args.preferences is None and not args.no_interactive and sys.stdin.isatty():
        pass
    elif args.preferences is None:
        print("starter defaults used. Review location, authorisation, floor and years before running the gate.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
