"""W2.4 — data-flow map test.

The project publishes a `docs/DATA-FLOW.md` table that lists every
module performing network I/O. The test asserts:

  1. The map file exists and is well-formed.
  2. Every network module actually present in the source tree is
     documented in the map.
  3. Every module documented in the map actually imports a network
     API (no zombie rows).
  4. The map can be regenerated by `python3 tools/build_dataflow_map.py`
     and the new content is identical to the committed one (the
     committed map is the source of truth; the tool is reproducible).

A new sender that adds an `import requests` without re-running the
tool fails (3) on the next test run. A removed sender that leaves a
stale row fails (2).

Run:  python3 -m unittest tests.test_dataflow_map -v
"""

from __future__ import annotations

import re
import subprocess
import sys
import unittest
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

MAP = ROOT / "docs" / "DATA-FLOW.md"
TOOL = ROOT / "tools" / "build_dataflow_map.py"
SRC_DIRS = [ROOT / "jobsearch", ROOT / "tools"]

# Import the network-name set from the tool so the test
# cannot drift from it. The test used to re-implement
# this set, which over time silently diverged from the
# tool -- by 6 entries (`http.server`, `ssl.wrap_socket`,
# `telegram.Bot`, `telegram.ext`, `urllib.parse`,
# `urllib.request` in the tool but missing from the test)
# and 2 entries (`ssl`, `urllib` in the test but
# generalised from the tool's specific entries). The
# divergence had not caused a real leak in the codebase
# (none of the specific-only entries are actually used),
# but it was a real contract drift: a contributor who
# trusted the test as a contract pin would have been
# surprised that the tool catches more APIs than the
# test asserts.
from tools.build_dataflow_map import NETWORK_NAMES  # noqa: E402


def _matches_network(imp: str) -> str | None:
    """Return the matching NETWORK_NAMES entry if `imp`
    is a network import, else None. Mirrors the tool's
    matching logic exactly (line 149 of
    `tools/build_dataflow_map.py`):
    `imp == net or imp.startswith(net + ".")`.
    The test used to use a different logic
    (`base_name = imp.split(".")[0]; base_name in
    NETWORK_NAMES`) which was both less precise (it
    only matched top-level names) and used a different
    NETWORK_NAMES set.
    """
    for net in NETWORK_NAMES:
        if imp == net or imp.startswith(net + "."):
            return net
    return None


def _find_network_modules_in_source() -> set[str]:
    """Walk the source tree and return the set of relative module
    paths that import a network API."""
    import ast
    found: set[str] = set()
    for base in SRC_DIRS:
        if not base.exists():
            continue
        for path in base.rglob("*.py"):
            try:
                tree = ast.parse(path.read_text(encoding="utf-8"))
            except (SyntaxError, OSError):
                continue
            for node in ast.walk(tree):
                names: list[str] = []
                if isinstance(node, ast.Import):
                    names.extend(a.name for a in node.names)
                elif isinstance(node, ast.ImportFrom):
                    if node.module:
                        names.append(node.module)
                for n in names:
                    if _matches_network(n) is not None:
                        found.add(str(path.relative_to(ROOT)))
                        break
    return found


def _read_documented_modules() -> set[str]:
    if not MAP.exists():
        return set()
    text = MAP.read_text(encoding="utf-8")
    # Match table rows: | `path/to/file.py` | `api` | ... |
    return set(re.findall(r"\|\s*`([^`]+\.py)`\s*\|", text))


class TestDataflowMap(unittest.TestCase):

    def test_map_file_exists(self) -> None:
        self.assertTrue(
            MAP.exists(),
            f"DATA-FLOW.md missing at {MAP.relative_to(ROOT)}. "
            f"Run: python3 tools/build_dataflow_map.py"
        )

    def test_every_network_module_is_documented(self) -> None:
        """A module in source that imports a network API but is not
        in the map is a build failure."""
        actual = _find_network_modules_in_source()
        documented = _read_documented_modules()
        missing = actual - documented
        if missing:
            self.fail(
                f"The following modules import a network API but are "
                f"NOT documented in {MAP.relative_to(ROOT)}:\n  "
                + "\n  ".join(sorted(missing))
                + "\nRun: python3 tools/build_dataflow_map.py"
            )

    def test_no_zombie_rows(self) -> None:
        """Every module in the map must actually import a network API.
        A row that no longer corresponds to a real import is stale
        documentation -- a build failure until the row is removed or
        the import is restored."""
        actual = _find_network_modules_in_source()
        documented = _read_documented_modules()
        zombies = documented - actual
        if zombies:
            self.fail(
                f"The following modules are listed in {MAP.relative_to(ROOT)} "
                f"but no longer import a network API:\n  "
                + "\n  ".join(sorted(zombies))
                + "\nRe-run tools/build_dataflow_map.py or restore the import."
            )

    def test_map_is_reproducible(self) -> None:
        """The committed map must be byte-identical to what the tool
        produces. A contributor who hand-edits the map and forgets to
        re-run the tool will fail this test."""
        if not MAP.exists() or not TOOL.exists():
            self.skipTest("Map or tool missing; nothing to compare.")
        result = subprocess.run(
            [sys.executable, str(TOOL)],
            capture_output=True,
            text=True,
            cwd=ROOT,
        )
        if result.returncode != 0:
            self.fail(
                f"tools/build_dataflow_map.py failed:\n{result.stdout}\n{result.stderr}"
            )
        on_disk = MAP.read_bytes()
        expected = (ROOT / "docs" / "DATA-FLOW.md").read_bytes()
        self.assertEqual(
            on_disk,
            expected,
            "DATA-FLOW.md is out of date. Re-run: python3 tools/build_dataflow_map.py"
        )

    def test_no_tbd_placeholders(self) -> None:
        """The shipped data flow map must not contain "TBD"
        placeholders. A "TBD" entry is a placeholder that
        ships in the public artifact and tells the reviewer
        nothing about what data leaves the machine.

        The tool used to write "TBD: reviewer to fill" for
        every row as a "conservative default". The new
        behaviour is to summarise the surface from the
        source: a literal URL, "user-supplied URL", or
        "stdlib parse only, no network call". A contributor
        who adds a new network import that the tool cannot
        summarise should fix the tool, not add a TBD row.
        """
        if not MAP.exists():
            self.skipTest("Map missing; nothing to check.")
        text = MAP.read_text(encoding="utf-8")
        # Look in the table body only. The header and the
        # prose sections may legitimately mention "TBD" as
        # a topic (e.g. "Today the only documented surface
        # is ..."), but the table cells are the contract.
        in_table = False
        bad_cells: list[str] = []
        for line in text.splitlines():
            if line.startswith("| Module"):
                in_table = True
                continue
            if not in_table:
                continue
            if not line.startswith("|"):
                in_table = False
                continue
            # Skip the separator row "|---|---|..."
            if "---" in line:
                continue
            cells = [c.strip() for c in line.split("|")]
            # cells[0] and cells[-1] are empty from the leading
            # and trailing pipes. The Surface cell is the last
            # meaningful one.
            if len(cells) < 5:
                continue
            surface = cells[-2]
            if "TBD" in surface or "TODO" in surface or "FIXME" in surface:
                bad_cells.append(surface)
        self.assertEqual(
            bad_cells, [],
            f"{MAP.relative_to(ROOT)} contains placeholder "
            f"surfaces that ship in the public artifact: "
            f"{bad_cells!r}. Either summarise the surface in "
            f"tools/build_dataflow_map.py or describe the call "
            f"site in the row."
        )

    def test_test_finder_matches_tool_finder(self) -> None:
        """The test's `_find_network_modules_in_source`
        and the tool's `_find_network_modules` must
        agree on the set of "network modules" in the
        source tree. The two functions implement the
        same intent ("which files import a network
        API?") but with different code paths, so they
        can drift in subtle ways:
        - the test used to have its own NETWORK_NAMES
          set that diverged from the tool's;
        - the test used to use top-level-name matching
          (split on ".") while the tool used
          exact-or-prefix matching.
        Both drift modes had been silently broken
        in this codebase until the test was patched
        to import the tool's NETWORK_NAMES and use
        `_matches_network` (which mirrors the tool's
        logic). This test pins the agreement so a
        contributor who "improves" either side
        (e.g. by adding regex matching to the tool,
        or by adding a top-level shortcut to the
        test) without updating the other fails
        the test with a precise error.

        The test runs both functions on the same
        source tree and asserts the resulting sets
        of relative file paths are identical. The
        shapes differ (the tool returns a list of
        (path, net) tuples; the test returns a set
        of relative paths), but the set of files
        that contain a network import should be the
        same.
        """
        # The test's finder (what the test's
        # assertions about "every network module
        # is documented" and "no zombie rows" are
        # based on).
        test_actual = _find_network_modules_in_source()
        # The tool's finder (what the DATA-FLOW.md
        # map is based on). Import directly to
        # avoid the test's own copy of the constant.
        from tools import build_dataflow_map
        tool_pairs = build_dataflow_map._find_network_modules()
        tool_actual = {
            str(p.relative_to(build_dataflow_map.ROOT))
            for p, _net in tool_pairs
        }
        # The two must agree on the set of files
        # that import a network API. If they
        # disagree, either the test or the tool
        # has a different definition of "network
        # API" -- which would mean the test's
        # "every network module is documented"
        # and "no zombie rows" assertions are
        # checking against the wrong set.
        only_in_test = test_actual - tool_actual
        only_in_tool = tool_actual - test_actual
        self.assertEqual(
            only_in_test, set(),
            f"the test's network-module finder "
            f"flags {len(only_in_test)} file(s) "
            f"the tool does not: "
            f"{sorted(only_in_test)}. Either the "
            f"test's matching logic is too loose "
            f"(it catches a non-network import) "
            f"or the tool's NETWORK_NAMES set is "
            f"missing an entry. See "
            f"_matches_network in this file and "
            f"_find_network_modules in "
            f"tools/build_dataflow_map.py."
        )
        self.assertEqual(
            only_in_tool, set(),
            f"the tool's network-module finder "
            f"flags {len(only_in_tool)} file(s) "
            f"the test does not: "
            f"{sorted(only_in_tool)}. Either the "
            f"tool's matching logic is too loose "
            f"or the test's NETWORK_NAMES set is "
            f"missing an entry. The test now "
            f"imports NETWORK_NAMES from the tool, "
            f"so a divergence here means the "
            f"matching logic differs (the test "
            f"uses _matches_network, the tool "
            f"uses an inline check at line 149)."
        )


if __name__ == "__main__":
    unittest.main()
